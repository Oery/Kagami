pub fn enchantment_id(name: &str) -> Option<u16> {
    ENCHANTMENTS.iter().position(|e| *e == name).map(|id| id as u16)
}

pub fn potion_id(name: &str) -> Option<u16> {
    POTIONS.iter().position(|p| *p == name).map(|id| id as u16)
}

pub fn mob_effect_id(name: &str) -> Option<u16> {
    MOB_EFFECTS.iter().position(|e| *e == name).map(|id| id as u16)
}
